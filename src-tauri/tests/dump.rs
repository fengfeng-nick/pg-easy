/// 以两个库可以互相比对的方式描述夹具里的对象：列定义、约束、索引、触发器、
/// 视图、外键，以及每张表行的顺序无关转储。
const CANONICAL: &str = "
    with rels as (
        select c.oid, n.nspname, c.relname
          from pg_class c join pg_namespace n on n.oid = c.relnamespace
         where n.nspname = 'fixture'
    ),
    cols as (
        select n.nspname || '.' || c.relname || ' ~ ' ||
               string_agg(a.attnum || ':' || a.attname || ' ' || format_type(a.atttypid, a.atttypmod) ||
                          case when a.attnotnull then ' not null' else '' end ||
                          coalesce(' default ' || pg_get_expr(d.adbin, d.adrelid), '') ||
                          case a.attidentity when 'a' then ' identity always'
                                             when 'd' then ' identity by default'
                                             else '' end ||
                          case a.attgenerated when 's' then ' generated' else '' end,
                          ', ' order by a.attnum) as line
          from pg_attribute a
          join pg_class c on c.oid = a.attrelid
          join pg_namespace n on n.oid = c.relnamespace
          left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
         where n.nspname = 'fixture' and a.attnum > 0 and not a.attisdropped
           and c.relkind in ('r', 'p')
         group by n.nspname, c.relname
    ),
    cons as (
        select conrelid || ' ~ ' || conname || ' ~ ' || pg_get_constraintdef(con.oid)
               || case convalidated when false then ' not valid' else '' end as line
          from pg_constraint con
         where connamespace = 'fixture'::regnamespace and contype <> 't'
           and conparentid = 0
    ),
    idx as (
        select pg_get_indexdef(i.indexrelid) as line
          from pg_index i
          join pg_class c on c.oid = i.indrelid
          join pg_namespace n on n.oid = c.relnamespace
         where n.nspname = 'fixture'
           and not exists (select 1 from pg_constraint con
                            where con.conindid = i.indexrelid and con.conrelid = i.indrelid)
    ),
    trig as (
        select pg_get_triggerdef(t.oid) as line
          from pg_trigger t join pg_class c on c.oid = t.tgrelid
          join pg_namespace n on n.oid = c.relnamespace
         where n.nspname = 'fixture' and not t.tgisinternal
    ),
    vws as (
        select n.nspname || '.' || c.relname || ' ~ ' || pg_get_viewdef(c.oid, true) as line
          from pg_class c join pg_namespace n on n.oid = c.relnamespace
         where n.nspname = 'fixture' and c.relkind in ('v', 'm')
    ),
    seqs as (
        select n.nspname || '.' || c.relname || ' ~ ' || s.seqmin || '..' || s.seqmax ||
               ' start ' || s.seqstart || ' inc ' || s.seqincrement as line
          from pg_sequence s join pg_class c on c.oid = s.seqrelid
          join pg_namespace n on n.oid = c.relnamespace
         where n.nspname = 'fixture'
           and not exists (select 1 from pg_depend dp
                            where dp.classid = 'pg_class'::regclass and dp.objid = c.oid
                              and dp.deptype = 'a')
    ),
    rows_users as (select 'data users ~ ' || u::text as line from fixture.users u),
    rows_orders as (select 'data orders ~ ' || o::text as line from fixture.orders o),
    rows_big as (select 'data big ~ ' || b::text as line from fixture.big b),
    rows_u as (select 'data U ~ ' || u::text as line from fixture.\"U\" u)
    select kind, line from (
        select 'column' as kind, line
          from (select line from cols union all select line from cons
                union all select line from idx union all select line from trig
                union all select line from vws union all select line from seqs) objects
        union all select 'data', line from rows_users
        union all select 'data', line from rows_orders
        union all select 'data', line from rows_big
        union all select 'data', line from rows_u
    ) s
    order by kind, line
";

fn params() -> Option<ConnectParams> {
    let url = std::env::var("PG_TEST_URL").ok()?;
    Some(ConnectParams {
        ssl: SslMode::Disable,
        ..testing::parse_url(&url)
    })
}

async fn connect(params: &ConnectParams) -> pg::Connection {
    let stream = testing::open_stream(params).await.expect("open socket");
    pg::connect(stream, &testing::startup_params(params))
        .await
        .expect("login")
}

async fn run(conn: &mut pg::Connection, sql: &str) -> Result<String, String> {
    match conn.run(sql, usize::MAX).await {
        Ok(output) => Ok(output
            .rows
            .map(|rows| {
                rows.values
                    .iter()
                    .map(|row| {
                        row[0].clone().unwrap_or_default()
                    })
                    .collect::<Vec<_>>()
                    .join("\u{1}")
            })
            .unwrap_or_default()),
        Err((error, _)) => Err(format!("{} {}", error.message, error.detail.unwrap_or_default())),
    }
}

/// 通过 `psql` 回放转储，就像用户会做的那样。设置 `ON_ERROR_STOP` 后 psql
/// 会在第一个错误处停下，所以这里设了；配合 `-i`，`docker exec` 会转发退出
/// 状态，失败的语句就是这样在这里暴露出来的。
///
/// 应用自己的客户端拒绝 `COPY ... FROM STDIN`，所以回放不能走它。
async fn replay(database: &str, script: &str) -> Result<(), String> {
    use std::io::Write;
    use std::process::{Command, Stdio};

    let container = std::env::var("PG_TEST_CONTAINER").unwrap_or_else(|_| "postgres18".into());
    let user = std::env::var("PG_TEST_USER").unwrap_or_else(|_| "root".into());
    let script = script.to_string();
    let database = database.to_string();
    tokio::task::spawn_blocking(move || {
        let mut child = Command::new("docker")
            .args([
                "exec", "-i", &container, "psql", "-U", &user, "-d", &database, "-q",
                "-v", "ON_ERROR_STOP=1",
            ])
            .stdin(Stdio::piped())
            .stdout(Stdio::null())
            .stderr(Stdio::piped())
            .spawn()
            .map_err(|err| format!("could not run docker: {err}"))?;
        child
            .stdin
            .take()
            .expect("stdin")
            .write_all(script.as_bytes())
            .map_err(|err| format!("write to psql: {err}"))?;
        let output = child.wait_with_output().map_err(|err| err.to_string())?;
        if output.status.success() {
            Ok(())
        } else {
            Err(String::from_utf8_lossy(&output.stderr).into_owned())
        }
    })
    .await
    .map_err(|err| err.to_string())?
}

#[tokio::test]
async fn a_dump_replays_into_an_identical_database() {
    let Some(params) = params() else {
        eprintln!("PG_TEST_URL not set; skipping");
        return;
    };
    let mut conn = connect(&params).await;

    let source = format!("fixture_{}", std::process::id());
    let target = format!("{source}_copy");
    for name in [&source, &target] {
        let _ = run(
            &mut conn,
            &format!("drop database if exists {name} with (force)"),
        )
        .await;
        run(&mut conn, &format!("create database {name}")).await.unwrap();
    }

    let in_source = ConnectParams {
        database: source.clone(),
        ..params.clone()
    };
    let raw = connect(&in_source).await;
    let mut session = pg_easy_lib::testing::dump::session("test", &in_source, &source, raw);
    run(&mut session.conn, FIXTURE).await.expect("fixture");
    let before = run(&mut session.conn, CANONICAL)
        .await
        .expect("describe source");

    let mut sink: Vec<u8> = Vec::new();
    let relations = pg_easy_lib::testing::dump::plan(&mut session, None, true)
        .await
        .expect("plan");
    let relations: Vec<_> = relations
        .into_iter()
        .filter(|relation| relation.schema == "fixture")
        .collect();
    pg_easy_lib::testing::dump::run(
        &mut session,
        &relations,
        &pg_easy_lib::testing::dump::DumpOptions {
            database: source.clone(),
            format: pg_easy_lib::testing::dump::DumpFormat::Sql,
            include_data: true,
        },
        &mut sink,
        &|| false,
    )
    .await
    .expect("dump");
    let script = String::from_utf8(sink).expect("utf-8 dump");

    replay(&target, &script).await.expect("replay the dump");
    let in_target = ConnectParams {
        database: target.clone(),
        ..params
    };
    let mut target_conn = connect(&in_target).await;
    let after = run(&mut target_conn, CANONICAL).await.expect("describe copy");

    assert_eq!(before, after, "the copy does not match its source");

    // 标识序列必须越过导入的 id 继续计数。
    let next = run(
        &mut target_conn,
        "insert into fixture.users (email, name) values ('d@x', 'Dee') returning id",
    )
    .await
    .unwrap();
    assert_eq!(next, "4");

    // 保持服务器维持原样。
    for name in [&target, &source] {
        let _ = run(&mut conn, &format!("drop database if exists {name} with (force)")).await;
    }
}

/// 同一个转储改用应用自己的导入器回放：`psql` 不再是必经之路，结构、数据
/// 和 `COPY … FROM STDIN` 的数据行都由本应用自己送进服务器。
#[tokio::test]
async fn a_dump_imports_through_the_app_into_an_identical_database() {
    let Some(params) = params() else {
        eprintln!("PG_TEST_URL not set; skipping");
        return;
    };
    let mut conn = connect(&params).await;

    let source = format!("imported_{}", std::process::id());
    let target = format!("{source}_copy");
    for name in [&source, &target] {
        let _ = run(
            &mut conn,
            &format!("drop database if exists {name} with (force)"),
        )
        .await;
        run(&mut conn, &format!("create database {name}")).await.unwrap();
    }

    let in_source = ConnectParams {
        database: source.clone(),
        ..params.clone()
    };
    let raw = connect(&in_source).await;
    let mut session = pg_easy_lib::testing::dump::session("test", &in_source, &source, raw);
    run(&mut session.conn, FIXTURE).await.expect("fixture");
    let before = run(&mut session.conn, CANONICAL)
        .await
        .expect("describe source");

    let mut sink: Vec<u8> = Vec::new();
    let relations = pg_easy_lib::testing::dump::plan(&mut session, None, true)
        .await
        .expect("plan");
    let relations: Vec<_> = relations
        .into_iter()
        .filter(|relation| relation.schema == "fixture")
        .collect();
    pg_easy_lib::testing::dump::run(
        &mut session,
        &relations,
        &pg_easy_lib::testing::dump::DumpOptions {
            database: source.clone(),
            format: pg_easy_lib::testing::dump::DumpFormat::Sql,
            include_data: true,
        },
        &mut sink,
        &|| false,
    )
    .await
    .expect("dump");
    let script = String::from_utf8(sink).expect("utf-8 dump");

    let in_target = ConnectParams {
        database: target.clone(),
        ..params
    };
    let raw = connect(&in_target).await;
    let mut target_conn =
        pg_easy_lib::testing::dump::session("test-target", &in_target, &target, raw);

    let plan = pg_easy_lib::testing::import::plan(&script).expect("plan the dump");
    let statements = plan.total();
    let outcome = pg_easy_lib::testing::import::run(
        &mut target_conn,
        plan,
        &pg_easy_lib::testing::import::ImportOptions {
            in_transaction: true,
        },
        &tokio_util::sync::CancellationToken::new(),
        script.len() as u64,
        |_| {},
    )
    .await
    .expect("import the dump");

    assert_eq!(outcome.statements, statements);
    assert!(
        outcome.copied_rows > 0,
        "the dump carries its rows through COPY blocks"
    );

    let after = run(&mut target_conn.conn, CANONICAL)
        .await
        .expect("describe copy");
    assert_eq!(before, after, "the imported database does not match its source");

    // 标识序列必须越过导入的 id 继续计数。
    let next = run(
        &mut target_conn.conn,
        "insert into fixture.users (email, name) values ('d@x', 'Dee') returning id",
    )
    .await
    .unwrap();
    assert_eq!(next, "4");

    for name in [&target, &source] {
        let _ = run(&mut conn, &format!("drop database if exists {name} with (force)")).await;
    }
}

/// 事务里的导入失败时不能留下半成品：结构和数据都该回到起点。
#[tokio::test]
async fn a_failed_import_leaves_nothing_behind() {
    let Some(params) = params() else {
        eprintln!("PG_TEST_URL not set; skipping");
        return;
    };
    let mut conn = connect(&params).await;

    let target = format!("imported_fail_{}", std::process::id());
    let _ = run(
        &mut conn,
        &format!("drop database if exists {target} with (force)"),
    )
    .await;
    run(&mut conn, &format!("create database {target}"))
        .await
        .unwrap();

    let in_target = ConnectParams {
        database: target.clone(),
        ..params
    };
    let raw = connect(&in_target).await;
    let mut session = pg_easy_lib::testing::dump::session("test", &in_target, &target, raw);

    let script = "\
create schema fixture_fail;
create table fixture_fail.t (a int);
insert into fixture_fail.t values (1);
select this_is_not_sql;
";
    let plan = pg_easy_lib::testing::import::plan(script).expect("plan");
    let error = pg_easy_lib::testing::import::run(
        &mut session,
        plan,
        &pg_easy_lib::testing::import::ImportOptions {
            in_transaction: true,
        },
        &tokio_util::sync::CancellationToken::new(),
        script.len() as u64,
        |_| {},
    )
    .await
    .err()
    .expect("the bogus statement fails");

    // 报错要指向文件里的第四条语句，而不是它所在的批次。
    assert_eq!(error.statement_index, Some(3));

    // 事务已回滚：前面建好的 schema 和表都不该留下。
    let exists = run(
        &mut session.conn,
        "select count(*) from pg_namespace where nspname = 'fixture_fail'",
    )
    .await
    .expect("count schemas");
    assert_eq!(exists, "0");

    let _ = run(&mut conn, &format!("drop database if exists {target} with (force)")).await;
}

